-- ── 1. Atomic counter for unique certificate numbers ─────────────────────────
-- This table holds a single row that is incremented atomically.
CREATE TABLE IF NOT EXISTS techtonic2_cert_counter (
  id      INTEGER PRIMARY KEY DEFAULT 1,         -- always 1
  current INTEGER NOT NULL DEFAULT 1000           -- last issued number; first cert = 1001
);

-- Seed the counter row (run only once)
INSERT INTO techtonic2_cert_counter (id, current)
VALUES (1, 1000)
ON CONFLICT (id) DO NOTHING;

-- ── 2. Atomic-increment RPC function ─────────────────────────────────────────
-- Called by the Python generator to get the next unique number safely.
CREATE OR REPLACE FUNCTION next_techtonic2_cert_number()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER   -- runs with owner privileges, safe to call via anon-ish service key
AS $$
DECLARE
  next_val INTEGER;
BEGIN
  UPDATE techtonic2_cert_counter
  SET    current = current + 1
  WHERE  id = 1
  RETURNING current INTO next_val;

  IF next_val IS NULL THEN
    RAISE EXCEPTION 'Certificate counter row not found. Seed techtonic2_cert_counter first.';
  END IF;

  RETURN next_val;
END;
$$;

-- ── 3. Certificates table ─────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "techtonic2.0_certificates" (
  certificate_id           TEXT        NOT NULL,
  name                     TEXT        NOT NULL,
  role                     TEXT        NOT NULL,
  member_id                BIGINT,                        -- Links to techtonic2.0_members(id); nullable for manual certs
  drive_file_id            TEXT,                          -- Google Drive file ID; set after upload
  certificate_generated_at TIMESTAMPTZ,                   -- Timestamp updated whenever certificate is generated
  created_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT techtonic20_certs_pk           PRIMARY KEY (certificate_id),
  CONSTRAINT techtonic20_certs_role_check   CHECK (role IN ('participant', 'team_member')),
  CONSTRAINT techtonic20_certs_name_notempty CHECK (LENGTH(TRIM(name)) > 0),
  CONSTRAINT techtonic20_certs_id_format    CHECK (certificate_id ~ '^TEC2_CICR_[0-9]+$')
);

-- Index for fast lookups by certificate_id (covered by PK, but explicit for clarity)
CREATE UNIQUE INDEX IF NOT EXISTS techtonic20_certs_id_idx
  ON "techtonic2.0_certificates" (certificate_id);

-- ── 4. Row Level Security (RLS) ───────────────────────────────────────────────
-- Enable RLS so only authorized callers can write; anyone can read for verification.
ALTER TABLE "techtonic2.0_certificates" ENABLE ROW LEVEL SECURITY;

-- Public can read certificate records (needed for verification page via service key)
CREATE POLICY "public_read_certificates"
  ON "techtonic2.0_certificates"
  FOR SELECT
  USING (true);

-- Only service role (backend) can insert/update/delete
-- (The anon key will be blocked from writes by RLS)
CREATE POLICY "service_role_write_certificates"
  ON "techtonic2.0_certificates"
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

-- ── 5. Secure the counter table as well ──────────────────────────────────────
ALTER TABLE techtonic2_cert_counter ENABLE ROW LEVEL SECURITY;

-- Only service role can touch the counter
CREATE POLICY "service_role_counter"
  ON techtonic2_cert_counter
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

-- Grant execute on RPC to service role only
REVOKE EXECUTE ON FUNCTION next_techtonic2_cert_number() FROM PUBLIC;
GRANT  EXECUTE ON FUNCTION next_techtonic2_cert_number() TO service_role;

-- ── 6. Members (Students/Participants) intake table ────────────────────────────
-- Simple intake table where you add the students/members to be issued certificates.
-- Contains only auto-generated primary ID, student name, and role.
CREATE TABLE IF NOT EXISTS "techtonic2.0_members" (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'participant',
  CONSTRAINT techtonic20_members_role_check CHECK (role IN ('participant', 'team_member')),
  CONSTRAINT techtonic20_members_name_notempty CHECK (LENGTH(TRIM(name)) > 0)
);

ALTER TABLE "techtonic2.0_members" ENABLE ROW LEVEL SECURITY;

-- Only service role and dashboard can manage members
CREATE POLICY "service_role_all_members"
  ON "techtonic2.0_members"
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

-- ── 7. Link Certificates to Members (Duplicate-Name Safe) ─────────────────────
-- Adds member_id to techtonic2.0_certificates to track which member already has a certificate.
-- This keeps techtonic2.0_members completely minimal (id, name, role) while ensuring
-- two students with the same name are never accidentally confused.
ALTER TABLE "techtonic2.0_certificates"
  ADD COLUMN IF NOT EXISTS member_id BIGINT
  REFERENCES "techtonic2.0_members"(id)
  ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS techtonic20_certs_member_id_idx
  ON "techtonic2.0_certificates" (member_id);

